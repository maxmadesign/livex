export type TextKey = Key;
const TABLES: Record<Lang, Record<Key, string>> = { en, zh, ja };

/** Looks up `key` in `lang` and fills {tokens} with plain (not yet escaped) values. */
export function t(lang: Lang, key: Key, values: Record<string, string | number> = {}): string {
  const template = TABLES[lang][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

export const tierKey = (tier: RarityTier): Key => `tier.${tier}` as Key;

